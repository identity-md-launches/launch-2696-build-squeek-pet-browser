export type MessageKey = keyof typeof messages;
export type Variables = Record<string, string | number>;
export const languageFor = (browser: string): Language => /^vi/i.test(browser) ? 'vi' : 'en';
export const localeFor = (language: Language) => language === 'vi' ? 'vi-VN' : 'en-US';
export function translate(language: Language, key: MessageKey, vars: Variables = {}): string {
  return messages[key][language === 'vi' ? 1 : 0].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
export function formatNumber(language: Language, value: number, digits = 0): string {
  return new Intl.NumberFormat(localeFor(language), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value);
}
export function formatPercent(language: Language, value: number): string {
  return new Intl.NumberFormat(localeFor(language), { style: 'percent', maximumFractionDigits: 0 }).format(value);
}
export function formatDate(language: Language, at: string | number | null): string {
  if (at === null || !Number.isFinite(new Date(at).getTime())) return translate(language, 'na');
  return new Intl.DateTimeFormat(localeFor(language), { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(new Date(at));
}
export function formatTime(language: Language, at: number): string {
  return new Intl.DateTimeFormat(localeFor(language), { hour: '2-digit', minute: '2-digit', hourCycle: 'h23', timeZone: 'UTC' }).format(at) + ' UTC';
}
export function relativeTime(language: Language, at: number, now: number): string {
  const seconds = Math.max(0, (now - at) / 1000);
  const [size, unit]: [number, Intl.RelativeTimeFormatUnit] = seconds < 60 ? [1, 'second'] : seconds < 3600 ? [60, 'minute'] : seconds < 86400 ? [3600, 'hour'] : [86400, 'day'];
  return new Intl.RelativeTimeFormat(localeFor(language), { numeric: 'always', style: 'short' }).format(-Math.floor(seconds / size), unit);
}
